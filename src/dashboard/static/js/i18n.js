let currentLang = localStorage.getItem("weather2farm_language") || "en";
export function getLang() { return currentLang; }
export function setLang(lang) {
  if (translations[lang]) {
    currentLang = lang;
    localStorage.setItem("weather2farm_language", lang);
    translateDOM();
    window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang } }));
  }
}
const missingKeys = new Set();

export function t(key, params = {}) {
    if (!key) return '';
    let str = translations[currentLang][key];
    if (!str) {
        str = translations["en"][key];
    }
    if (!str) {
        if (!missingKeys.has(key)) {
            console.warn("[i18n] missing key:", key);
            missingKeys.add(key);
        }
        const parts = key.split(/[\._]/);
        let fallback = parts[parts.length - 1] || key;
        fallback = fallback.replace(/_/g, ' ');
        fallback = fallback.charAt(0).toUpperCase() + fallback.slice(1);
        str = fallback;
    }

    for (const [k, v] of Object.entries(params)) {
      let val = v;
      if (typeof val === 'string' && translations[currentLang][val]) {
          val = translations[currentLang][val];
      }
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), val);
    }
    return str;
}

window.checkI18n = function() {
    const missing = [];
    const langs = ['en', 'hi', 'mr'];
    
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const k = el.getAttribute("data-i18n");
        langs.forEach(l => {
            if (!translations[l][k]) missing.push(`[${l}] DOM: ${k}`);
        });
    });
    
    Object.keys(translations['en']).forEach(k => {
        langs.forEach(l => {
            if (!translations[l][k]) missing.push(`[${l}] Dict: ${k}`);
        });
    });

    missingKeys.forEach(k => {
         langs.forEach(l => {
            if (!translations[l][k]) missing.push(`[${l}] Runtime: ${k}`);
        });
    });

    const uniqueMissing = [...new Set(missing)];
    console.log("i18n Check Results:\n", uniqueMissing.length ? uniqueMissing.join("\n") : "All good!");
    return uniqueMissing;
};
  export function translateDOM() {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (translations[currentLang][key]) {
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        el.placeholder = translations[currentLang][key];
      } else {
        el.innerHTML = translations[currentLang][key];
      }
    }
  });
  
  document.querySelectorAll("select[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (translations[currentLang][key] && el.options.length > 0 && el.options[0].value === "") {
        el.options[0].text = translations[currentLang][key];
    }
  });

  document.title = t("app.title") + " — " + t("app.subtitle");
  

}
